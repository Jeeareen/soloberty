import type { AppEvent } from '../../types/event';

function daysFromNow(days: number, hour = 19, minute = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

